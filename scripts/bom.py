"""Write the living bill of materials for the front office: docs/bom.md.

Usage: python scripts/bom.py

Everything an auditor, a new engineer or the next model upgrade needs to know
about what's running, generated from the files that define it, so it can't
drift from them: models, agents and their grants, guardrails, services and
their pinned dependencies, Google Cloud APIs, cloud identities and roles, and
the prices the cost report assumes.

Copyright 2026 Robert H. Mowery III. Licensed under the Apache License, Version 2.0.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from brightwater.config import load_app  # noqa: E402


def services() -> list[tuple[str, list[str]]]:
    out = []
    for req in sorted((ROOT / "services").glob("*/requirements.txt")):
        pins = [line.strip() for line in req.read_text().splitlines() if line.strip() and not line.startswith("#")]
        out.append((req.parent.name, pins))
    return out


def apis() -> list[str]:
    tf = "\n".join(p.read_text() for p in (ROOT / "infra" / "terraform").glob("*.tf"))
    return sorted(set(re.findall(r'"([a-z0-9-]+\.googleapis\.com)"', tf)))


def commerce_model() -> str:
    text = (ROOT / "services" / "commerce-agent" / "app" / "agent.py").read_text()
    match = re.search(r'COMMERCE_MODEL", "([^"]+)"', text)
    return match.group(1) if match else "unknown"


def main() -> int:
    spec = load_app()
    authority = yaml.safe_load((ROOT / "agent" / "authority.yaml").read_text())
    lines = [
        "# Bill of materials: Brightwater front office",
        "",
        "Generated by `scripts/bom.py` from the repository. Do not edit by hand.",
        "",
        "## Models",
        "",
        "| Component | Model |",
        "| --- | --- |",
        f"| Front desk (CX Agent Studio) | `{spec.model}` |",
        f"| LLM guardrails | `{spec.model}` |",
        f"| Commerce agent (ADK, Vertex AI) | `{commerce_model()}` |",
        "",
        "## Agents and their grants",
        "",
    ]
    for agent in spec.agents:
        ops = [op for ref in agent.toolsets for op in ref.tools]
        lines.append(f"**{agent.display_name}** (`{agent.id}`)")
        lines.append("")
        lines.append(f"- Operations: {', '.join(f'`{o}`' for o in ops) or 'none'}")
        lines.append(f"- System tools: {', '.join(f'`{t}`' for t in agent.system_tools) or 'none'}")
        lines.append(f"- Delegates to: {', '.join(f'`{r}`' for r in agent.remote_agents) or 'none'}")
        lines.append("")
    for name, actor in authority["actors"].items():
        lines.append(f"**{name}** may never:")
        lines.extend(f"- {n}" for n in actor.get("never", []))
        lines.append("")
    lines += ["## Guardrails", "", "| ID | Kind | Scope | Fails |", "| --- | --- | --- | --- |"]
    for g in spec.guardrails:
        fails = "n/a (deterministic)" if g.kind == "regex" else ("open" if g.fail_open else "closed")
        lines.append(f"| `{g.id}` | {g.kind} | {g.scope} | {fails} |")
    lines += ["", "## Services and pinned dependencies", ""]
    for name, pins in services():
        lines.append(f"**{name}**: " + ", ".join(f"`{p}`" for p in pins))
        lines.append("")
    lines += ["## Google Cloud APIs", "", ", ".join(f"`{a}`" for a in apis()), ""]
    lines += ["## Cloud identities", "", "| Identity | Roles |", "| --- | --- |"]
    for identity, spec_ in authority["cloud_identities"].items():
        lines.append(f"| `{identity}` | {', '.join(f'`{r}`' for r in spec_['roles'])} |")
    lines += [
        "",
        "## Prices assumed",
        "",
        "- CX Agent Studio: $0.50 per session (chat or voice); voice past 300 seconds at $0.0025 per second.",
        "  Source: Google Cloud pricing page, checked 2026-10-14.",
        "",
    ]
    out = ROOT / "docs" / "bom.md"
    out.write_text("\n".join(lines))
    print(f"Wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
